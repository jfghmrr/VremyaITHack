import { expect, test } from "@playwright/test";
import { fakeMic } from "./fake-mic";
import { shoot } from "./shoot";

test("одиночный путь: каталог → микрофон → пение → разбор → A/B → тренировка → вызов", async ({ page, context }) => {
  await fakeMic(context, "cn-earth", { shift: -5, errors: [[500, 610, 2]] });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Перепев" })).toBeVisible();
  await shoot(page, "home");
  await page.getByRole("link", { name: "Начать петь" }).click();
  await expect(page.getByRole("heading", { name: "Выбор песни" })).toBeVisible();
  await page.getByRole("searchbox").fill("Земное притяжение");
  await page.getByRole("button", { name: "Петь «Земное притяжение»" }).click();
  await expect(page.getByRole("heading", { name: "Проверка микрофона" })).toBeVisible();
  await page.getByRole("button", { name: "Включить микрофон" }).click();
  await expect(page.getByRole("button", { name: "Начать пение" })).toBeEnabled();
  await expect(page.getByRole("combobox", { name: "Устройство ввода" })).toContainText("Встроенный микрофон");
  await shoot(page, "mic-check");
  await page.keyboard.press("Space");
  await expect(page.getByLabel("Пение")).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Основная навигация" })).toHaveCount(0);
  await page.waitForTimeout(9000);
  await shoot(page, "stage");
  await expect(page.getByRole("heading", { name: /Чисто|Хорошая попытка/ })).toBeVisible({ timeout: 40_000 });
  await expect(page).toHaveURL(/\/result$/);
  const score = Number(await page.getByLabel(/из 100/).getAttribute("aria-label").then((s) => s!.split(" ")[0]));
  expect(score).toBeGreaterThan(80);
  await expect(page.getByText("−5 полутонов")).toBeVisible();
  await expect(page.getByText("без штрафа")).toBeVisible();
  await page.waitForTimeout(900);
  await shoot(page, "result");
  await page.getByRole("button", { name: "Разбор и ошибки" }).click();
  await shoot(page, "result-analysis", [[1366,768],[1920,1080]]);
  // Намеренная ошибка на 5–6 с должна попасть в замечания.
  await expect(page.getByRole("listitem").filter({ hasText: "центов выше" }).first()).toBeVisible();
  await page.getByRole("button", { name: "Слушать попытку" }).click();
  await page.getByRole("button", { name: "Ориентир" }).click();
  await expect(page.getByRole("button", { name: "Ориентир" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("combobox", { name: "Источник ориентира" }).selectOption("voice");
  await page.getByRole("button", { name: "Слушать попытку" }).click();
  await page.getByRole("button", { name: "Мой голос, исправленный" }).click();
  await expect(page.getByRole("button", { name: "Мой голос, исправленный" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Как пел", exact: true }).click();
  await page.getByRole("button", { name: "Остановить", exact: true }).click();
  await page.getByRole("button", { name: "Переслушать", exact: true }).first().click();
  await expect(page.locator(".moments li.active")).toBeVisible();
  await page.locator(".moments li.active").getByRole("button", { name: "Остановить", exact: true }).click();
  await page.getByRole("button", { name: "Поделиться" }).click();
  await expect(page.getByText(/Ссылка скопирована|Скопируй ссылку/)).toBeVisible();
  const link = await page.evaluate(() => navigator.clipboard.readText().catch(() => ""));
  expect(link).toMatch(/#echo=[-_A-Za-z0-9]+$/);
  await page.getByRole("button", { name: "Потренировать" }).first().click();
  await expect(page.getByText("Тренировка без оценки")).toBeVisible();
  await page.getByRole("checkbox", { name: "По кругу" }).check();
  await page.getByRole("button", { name: "Спеть фрагмент" }).click();
  await expect(page.getByRole("button", { name: "Остановить", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Остановить", exact: true }).click();
  await page.getByRole("link", { name: "← К разбору" }).click();
  await expect(page).toHaveURL(/\/result$/);
  // Возврат к последнему разбору из каталога.
  await page.getByRole("link", { name: "Песни", exact: true }).click();
  await shoot(page, "songs");
  await page.getByRole("link", { name: /Последний разбор/ }).click();
  await expect(page).toHaveURL(/\/result$/);
  await page.keyboard.press("r");
  await expect(page).toHaveURL(/\/sing\/cn-earth$/);
  await page.getByRole("checkbox", { name: /Против своего рекорда/ }).check();
  await expect(page.getByText(/Против призрака: Твой рекорд/)).toBeVisible();
  await page.getByRole("checkbox", { name: /Против своего рекорда/ }).uncheck();
  await expect(page.getByText(/Против призрака: Твой рекорд/)).toHaveCount(0);
});
